var orderedTens = [...]uint64{10000000000000000000, 1000000000000000000, 100000000000000000, 10000000000000000, 1000000000000000, 100000000000000, 10000000000000, 1000000000000, 100000000000, 10000000000, 1000000000, 100000000, 10000000, 1000000, 100000, 10000, 1000, 100, 10, 1}

// Source exponent saturation precedes fraction adjustment and zero handling.
func orderedLockExponent(magnitude, digits uint64, negative bool) int64 {
	if digits >= 20 || magnitude > math.MaxInt64 {
		if negative {
			return math.MinInt64
		}
		return math.MaxInt64
	}
	if negative {
		return -int64(magnitude)
	}
	return int64(magnitude)
}

func orderedLockFractionExponent(exponent int64, fractionDigits uint64) int64 {
	// Explicit compatibility definition from the pinned E1-E4 observations;
	// this is not a claim that signed C overflow is portable.
	return int64(uint64(exponent) - fractionDigits)
}

func orderedLockParseFloat(token string, mantissaDigits uint64, exponent int64, negative bool) (float64, error) {
	if exponent > math.MaxInt32 {
		if negative {
			return math.Inf(-1), nil
		}
		return math.Inf(1), nil
	}
	zero := 0.0
	if negative {
		zero = math.Copysign(0, -1)
	}
	if exponent < math.MinInt32 {
		return zero, nil
	}
	// Avoid converting the unsigned count to platform int. Only a negative
	// exponent can enter the source's tiny-value branches.
	if exponent < -324 && mantissaDigits < uint64(-exponent-324) {
		return zero, nil
	}
	value, err := strconv.ParseFloat(token, 64)
	if err != nil {
		if n, ok := err.(*strconv.NumError); ok && n.Err == strconv.ErrRange {
			return value, nil
		}
		return 0, fmt.Errorf("ordered lock: validated float conversion failed: %w", err)
	}
	return value, nil
}

const orderedHiddenBit uint64 = 0x0010000000000000

func orderedCachedPower(exp int) (orderedFP, int) {
	approx := int(float64(-(exp + 87)) * 0.30102999566398114)
	idx := (approx + 348) / 8
	for {
		current := exp + orderedPowersTen[idx].exp + 64
		if current < -60 {
			idx++
			continue
		}
		if current > -32 {
			idx--
			continue
		}
		return orderedPowersTen[idx], -348 + idx*8
	}
}

func orderedBuildFP(value float64) orderedFP {
	bits := math.Float64bits(value)
	fp := orderedFP{frac: bits & 0x000fffffffffffff, exp: int((bits & 0x7ff0000000000000) >> 52)}
	if fp.exp != 0 {
		fp.frac += orderedHiddenBit
		fp.exp -= 1075
	} else {
		fp.exp = -1074
	}
	return fp
}

func orderedNormalize(fp *orderedFP) {
	for fp.frac&orderedHiddenBit == 0 {
		fp.frac <<= 1
		fp.exp--
	}
	fp.frac <<= 11
	fp.exp -= 11
}

func orderedBoundaries(fp orderedFP) (orderedFP, orderedFP) {
	upper := orderedFP{frac: (fp.frac << 1) + 1, exp: fp.exp - 1}
	for upper.frac&(orderedHiddenBit<<1) == 0 {
		upper.frac <<= 1
		upper.exp--
	}
	upper.frac <<= 10
	upper.exp -= 10
	shift := 1
	if fp.frac == orderedHiddenBit {
		shift = 2
	}
	lower := orderedFP{frac: (fp.frac << shift) - 1, exp: fp.exp - shift}
	lower.frac <<= lower.exp - upper.exp
	lower.exp = upper.exp
	return lower, upper
}

func orderedMultiply(a, b orderedFP) orderedFP {
	const mask uint64 = 0xffffffff
	ahbl, albh := (a.frac>>32)*(b.frac&mask), (a.frac&mask)*(b.frac>>32)
	albl, ahbh := (a.frac&mask)*(b.frac&mask), (a.frac>>32)*(b.frac>>32)
	tmp := (ahbl & mask) + (albh & mask) + (albl >> 32)
	tmp += 1 << 31
	return orderedFP{ahbh + (ahbl >> 32) + (albh >> 32) + (tmp >> 32), a.exp + b.exp + 64}
}

func orderedRoundDigit(digits []byte, delta, rem, kappa, frac uint64) {
	for rem < frac && delta-rem >= kappa && (rem+kappa < frac || frac-rem > rem+kappa-frac) {
		digits[len(digits)-1]--
		rem += kappa
	}
}

func orderedGenerateDigits(fp, upper, lower orderedFP, k *int) []byte {
	wfrac, delta := upper.frac-fp.frac, upper.frac-lower.frac
	one := orderedFP{uint64(1) << (-upper.exp), upper.exp}
	part1, part2 := upper.frac>>(-one.exp), upper.frac&(one.frac-1)
	digits := make([]byte, 0, 18)
	kappa := 10
	for divIndex := 10; kappa > 0; divIndex++ {
		div := orderedTens[divIndex]
		digit := part1 / div
		if digit != 0 || len(digits) != 0 {
			digits = append(digits, byte(digit)+'0')
		}
		part1 -= digit * div
		kappa--
		tmp := (part1 << (-one.exp)) + part2
		if tmp <= delta {
			*k += kappa
			orderedRoundDigit(digits, delta, tmp, div<<(-one.exp), wfrac)
			return digits
		}
	}
	for unit := 18; ; unit-- {
		part2 *= 10
		delta *= 10
		kappa--
		digit := part2 >> (-one.exp)
		if digit != 0 || len(digits) != 0 {
			digits = append(digits, byte(digit)+'0')
		}
		part2 &= one.frac - 1
		if part2 < delta {
			*k += kappa
			orderedRoundDigit(digits, delta, part2, one.frac, wfrac*orderedTens[unit])
			return digits
		}
	}
}

func orderedLockFloatString(value float64) string {
	negative := math.Signbit(value)
	sign := ""
	if negative {
		sign = "-"
	}
	if value == 0 {
		return sign + "0.0"
	}
	// Nonfinite values have already been rejected by the generator.
	w := orderedBuildFP(value)
	lower, upper := orderedBoundaries(w)
	orderedNormalize(&w)
	cp, power := orderedCachedPower(upper.exp)
	w, upper, lower = orderedMultiply(w, cp), orderedMultiply(upper, cp), orderedMultiply(lower, cp)
	lower.frac++
	upper.frac--
	k := -power
	digits := orderedGenerateDigits(w, upper, lower, &k)
	n := len(digits)
	exp := k + n - 1
	if exp < 0 {
		exp = -exp
	}
	if k >= 0 && exp < 15 {
		return sign + string(digits) + strings.Repeat("0", k) + ".0"
	}
	if k < 0 && (k > -7 || exp < 10) {
		offset := n + k
		if offset <= 0 {
			return sign + "0." + strings.Repeat("0", -offset) + string(digits)
		}
		return sign + string(digits[:offset]) + "." + string(digits[offset:])
	}
	limit := 18
	if negative {
		limit--
	}
	if n > limit {
		n = limit
	}
	text := string(digits[:1])
	if n > 1 {
		text += "." + string(digits[1:n])
	}
	expSign := "+"
	if k+n-1 < 0 {
		expSign = "-"
	}
	return sign + text + "e" + expSign + strconv.Itoa(exp)
}
