//! Ruby-compatible local configuration templates. Init owns these literal
//! reserved paths; other configuration writers retain their path restrictions.

use crate::{
    app::Context,
    configuration::{ConfigRoot, MutationGuard, MutationLock},
    error::ConfctlError,
    events::{EventSink, OutputStream, Style, UiEvent},
};
use std::{
    fs,
    io::Write,
    os::unix::fs::{DirBuilderExt, OpenOptionsExt},
};
use tokio_util::sync::CancellationToken;

pub(super) async fn run(root: ConfigRoot, ctx: &Context) -> Result<(), ConfctlError> {
    initialize(&root, &ctx.events, &ctx.cancellation, create).await
}

async fn initialize(
    root: &ConfigRoot,
    events: &EventSink,
    cancellation: &CancellationToken,
    create: impl Fn(
        &ConfigRoot,
        &MutationGuard,
        &'static str,
        Option<&[u8]>,
    ) -> Result<(), ConfctlError>,
) -> Result<(), ConfctlError> {
    require_empty(root)?;
    let guard = MutationLock::acquire(root, cancellation).await?;
    require_empty(root)?;
    for &(path, contents) in TEMPLATES {
        let result = async {
            canceled(cancellation)?;
            events
                .emit(UiEvent::Diagnostic {
                    stream: OutputStream::Stdout,
                    style: Style::Plain,
                    text: format!(
                        "{} {path}\n",
                        if contents.is_some() {
                            "mkfile"
                        } else {
                            "mkdir"
                        }
                    ),
                })
                .await?;
            // An acknowledgement may succeed while its consumer cancels.
            canceled(cancellation)?;
            create(root, &guard, path, contents)?;
            canceled(cancellation)
        }
        .await;
        result.map_err(|error: ConfctlError| {
            error.with_secondary(vec![ConfctlError::State(format!(
                "init stopped at {path}; partial configuration retained in {}",
                root.path().display()
            ))])
        })?;
    }
    Ok(())
}

fn canceled(cancellation: &CancellationToken) -> Result<(), ConfctlError> {
    if cancellation.is_cancelled() {
        Err(ConfctlError::Cancelled)
    } else {
        Ok(())
    }
}

fn require_empty(root: &ConfigRoot) -> Result<(), ConfctlError> {
    let entries = fs::read_dir(root.path()).map_err(|source| ConfctlError::Io {
        operation: "inspect init directory",
        path: Some(root.path().into()),
        source,
    })?;
    for entry in entries {
        let entry = entry.map_err(|source| ConfctlError::Io {
            operation: "inspect init directory entry",
            path: Some(root.path().into()),
            source,
        })?;
        if !["shell.nix", ".confctl", ".gems", ".gitignore"]
            .iter()
            .any(|name| entry.file_name() == *name)
        {
            return Err(ConfctlError::Configuration(
                "init must be called in an empty directory".into(),
            ));
        }
    }
    Ok(())
}

// The caller holds the one configuration lock through every notice and write.
// create_new refuses races and retains earlier effects, including a short file
// if a write fails. No existing destination is merged, truncated or chmodded.
fn create(
    root: &ConfigRoot,
    guard: &MutationGuard,
    relative: &'static str,
    contents: Option<&[u8]>,
) -> Result<(), ConfctlError> {
    guard.require_root(root)?;
    let path = root.path().join(relative);
    let result = if let Some(contents) = contents {
        fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o644)
            .open(&path)
            .and_then(|mut file| file.write_all(contents))
    } else {
        fs::DirBuilder::new().mode(0o755).create(&path)
    };
    result.map_err(|source| ConfctlError::Io {
        operation: "create init template",
        path: Some(path),
        source,
    })
}

