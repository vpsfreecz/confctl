use super::*;
use std::os::unix::ffi::OsStringExt;

fn fixture() -> (tempfile::TempDir, ConfigRoot) {
    let directory = tempfile::tempdir().unwrap();
    fs::create_dir(directory.path().join("cluster")).unwrap();
    fs::write(directory.path().join("flake.nix"), "{}\n").unwrap();
    fs::write(directory.path().join("cluster/cluster.nix"), "old core\n").unwrap();
    let root = ConfigRoot::new(directory.path()).unwrap();
    (directory, root)
}

#[tokio::test]
async fn acknowledged_core_notice_cancellation_keeps_only_earlier_effects() {
    for boundary in 0..4 {
        let (_directory, root) = fixture();
        let action = Action::Add {
            name: "nested/new".into(),
        };
        let cancellation = CancellationToken::new();
        let stop = cancellation.clone();
        let guard = MutationLock::acquire(&root, &cancellation).await.unwrap();
        let observed = root.clone();
        let (events, mut receiver) = EventSink::channel(1);
        let operation =
            tokio::spawn(async move { core(&action, &root, &guard, &events, &stop).await });
        for _ in 0..boundary {
            receiver.receive().await.unwrap().acknowledge(Ok(()));
        }
        let delivery = receiver.receive().await.unwrap();
        cancellation.cancel();
        delivery.acknowledge(Ok(()));
        assert!(operation.await.unwrap().unwrap_err().is_cancelled());
        for (index, path) in [
            "cluster/nested/new",
            "cluster/nested/new/module.nix",
            "cluster/nested/new/config.nix",
        ]
        .iter()
        .enumerate()
        {
            assert_eq!(observed.path().join(path).exists(), index < boundary);
        }
        assert_eq!(
            fs::read(observed.path().join("cluster/cluster.nix")).unwrap(),
            b"old core\n"
        );
        assert!(receiver.receive().await.is_none());
    }
}

#[tokio::test]
async fn failed_final_core_notice_and_conflicting_template_preserve_prefix() {
    for conflict in [false, true] {
        let (_directory, root) = fixture();
        let observed = root.clone();
        let action = Action::Add { name: "new".into() };
        let cancellation = CancellationToken::new();
        let guard = MutationLock::acquire(&root, &cancellation).await.unwrap();
        let (events, mut receiver) = EventSink::channel(1);
        let operation =
            tokio::spawn(async move { core(&action, &root, &guard, &events, &cancellation).await });
        receiver.receive().await.unwrap().acknowledge(Ok(()));
        receiver.receive().await.unwrap().acknowledge(Ok(()));
        let delivery = receiver.receive().await.unwrap();
        if conflict {
            fs::write(
                observed.path().join("cluster/new/config.nix"),
                b"external edit",
            )
            .unwrap();
            delivery.acknowledge(Ok(()));
        } else {
            delivery.acknowledge(Ok(()));
            receiver
                .receive()
                .await
                .unwrap()
                .acknowledge(Err("fixture output failed".into()));
        }
        assert!(operation.await.unwrap().is_err());
        assert!(observed.path().join("cluster/new/module.nix").is_file());
        if conflict {
            assert_eq!(
                fs::read(observed.path().join("cluster/new/config.nix")).unwrap(),
                b"external edit"
            );
        }
        assert_eq!(
            fs::read(observed.path().join("cluster/cluster.nix")).unwrap(),
            b"old core\n"
        );
        assert!(receiver.receive().await.is_none());
    }
}

#[test]
fn native_templates_and_discovery_do_not_normalize_names() {
    let (_directory, root) = fixture();
    let name = PathBuf::from(std::ffi::OsString::from_vec(b"native\xff/odd\"\n".to_vec()));
    let (module, config) = templates(&name);
    assert!(
        module
            .windows(b"cluster.\"native\xff/odd\"\n\"".len())
            .any(|value| value == b"cluster.\"native\xff/odd\"\n\"")
    );
    assert!(
        config
            .windows(b"native\xff-odd\"\n".len())
            .any(|value| value == b"native\xff-odd\"\n")
    );
    let path = root.path().join("cluster").join(&name);
    fs::create_dir_all(&path).unwrap();
    fs::write(path.join("module.nix"), module).unwrap();
    fs::write(path.join("config.nix"), config).unwrap();
    assert_eq!(discovered(&root, &CancellationToken::new()).unwrap(), b"# This file is generated by confctl, changes will be lost\n[\n  ./native\xff/odd\"\n/module.nix\n]\n");
}

#[tokio::test]
async fn failed_core_rename_retains_its_fresh_sibling_and_prior_core_object() {
    let (_directory, root) = fixture();
    fs::remove_file(root.path().join("cluster/cluster.nix")).unwrap();
    fs::create_dir(root.path().join("cluster/cluster.nix")).unwrap();
    let guard = MutationLock::acquire(&root, &CancellationToken::new())
        .await
        .unwrap();
    assert!(replace_core(&root, &guard, b"new core").is_err());
    assert!(root.path().join("cluster/cluster.nix").is_dir());
    let siblings = fs::read_dir(root.path().join("cluster"))
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| {
            path.file_name()
                .unwrap()
                .as_bytes()
                .starts_with(b"cluster.nix.new-")
        })
        .collect::<Vec<_>>();
    assert_eq!(siblings.len(), 1);
    assert_eq!(fs::read(&siblings[0]).unwrap(), b"new core");
}
