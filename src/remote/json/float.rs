//! Safe Rust port of JSON 2.21.2's vendor/fpconv.c (night-shift/fpconv), including
//! Ruby JSON's integer-float suffix and decimal/exponent emission rules. Keep
//! the original cached powers and Grisu2 rounding; std float display is not the
//! frozen Ruby serializer. Nonfinite values are rejected by the caller.

#[derive(Clone, Copy)]
struct Fp {
    fraction: u64,
    exponent: i32,
}
const HIDDEN: u64 = 1 << 52;

// Cached powers are copied mechanically from the qualified source; the full
// source SHA256 is retained with the Ruby semantic probe evidence.
mod powers;
use powers::POWERS;

fn normalize(mut value: Fp) -> Fp {
    while value.fraction & HIDDEN == 0 {
        value.fraction <<= 1;
        value.exponent -= 1;
    }
    value.fraction <<= 11;
    value.exponent -= 11;
    value
}
fn multiply(a: Fp, b: Fp) -> Fp {
    let rounded = (u128::from(a.fraction) * u128::from(b.fraction) + (1u128 << 63)) >> 64;
    Fp {
        fraction: rounded as u64,
        exponent: a.exponent + b.exponent + 64,
    }
}
fn round_digit(digits: &mut [u8], delta: u64, mut remainder: u64, kappa: u64, fraction: u64) {
    while remainder < fraction
        && delta - remainder >= kappa
        && (remainder + kappa < fraction || fraction - remainder > remainder + kappa - fraction)
    {
        *digits.last_mut().expect("generated digit") -= 1;
        remainder += kappa;
    }
}
fn generate(value: Fp, upper: Fp, lower: Fp, exponent: &mut i32) -> Vec<u8> {
    let fraction = upper.fraction - value.fraction;
    let mut delta = upper.fraction - lower.fraction;
    let shift = (-upper.exponent) as u32;
    let one = 1u64 << shift;
    let mut part1 = upper.fraction >> shift;
    let mut part2 = upper.fraction & (one - 1);
    let mut digits = Vec::with_capacity(18);
    let mut kappa = 10;
    let mut divisor = 1_000_000_000u64;
    while kappa > 0 {
        let digit = (part1 / divisor) as u8;
        if digit != 0 || !digits.is_empty() {
            digits.push(b'0' + digit);
        }
        part1 -= u64::from(digit) * divisor;
        kappa -= 1;
        let remainder = (part1 << shift) + part2;
        if remainder <= delta {
            *exponent += kappa;
            round_digit(&mut digits, delta, remainder, divisor << shift, fraction);
            return digits;
        }
        divisor /= 10;
    }
    let mut unit = 10u64;
    loop {
        part2 = part2.wrapping_mul(10);
        delta = delta.wrapping_mul(10);
        kappa -= 1;
        let digit = (part2 >> shift) as u8;
        if digit != 0 || !digits.is_empty() {
            digits.push(b'0' + digit);
        }
        part2 &= one - 1;
        if part2 < delta {
            *exponent += kappa;
            round_digit(&mut digits, delta, part2, one, fraction.wrapping_mul(unit));
            return digits;
        }
        unit = unit.wrapping_mul(10);
    }
}
fn grisu(value: f64) -> (Vec<u8>, i32) {
    let bits = value.to_bits();
    let encoded_exponent = ((bits >> 52) & 0x7ff) as i32;
    let original = Fp {
        fraction: (bits & 0x000f_ffff_ffff_ffff) + if encoded_exponent != 0 { HIDDEN } else { 0 },
        exponent: if encoded_exponent != 0 {
            encoded_exponent - 1075
        } else {
            -1074
        },
    };
    let mut upper = Fp {
        fraction: (original.fraction << 1) + 1,
        exponent: original.exponent - 1,
    };
    while upper.fraction & (HIDDEN << 1) == 0 {
        upper.fraction <<= 1;
        upper.exponent -= 1;
    }
    upper.fraction <<= 10;
    upper.exponent -= 10;
    let lower_shift = if original.fraction == HIDDEN { 2 } else { 1 };
    let lower_exponent = original.exponent - lower_shift;
    let mut lower = Fp {
        fraction: ((original.fraction << lower_shift) - 1) << (lower_exponent - upper.exponent),
        exponent: upper.exponent,
    };
    let value = normalize(original);
    let approx = (-(upper.exponent + 87) as f64 * f64::from_bits(0x3fd34413509f79fe)) as i32;
    let mut index = ((approx + 348) / 8) as usize;
    loop {
        let current = upper.exponent + POWERS[index].1 + 64;
        if current < -60 {
            index += 1;
        } else if current > -32 {
            index -= 1;
        } else {
            break;
        }
    }
    let power = Fp {
        fraction: POWERS[index].0,
        exponent: POWERS[index].1,
    };
    let value = multiply(value, power);
    upper = multiply(upper, power);
    lower = multiply(lower, power);
    lower.fraction += 1;
    upper.fraction -= 1;
    let mut exponent = 348 - index as i32 * 8;
    let digits = generate(value, upper, lower, &mut exponent);
    (digits, exponent)
}

pub(super) fn format(value: f64) -> String {
    debug_assert!(value.is_finite());
    let negative = value.is_sign_negative();
    let sign = if negative { "-" } else { "" };
    if value == 0.0 {
        return format!("{sign}0.0");
    }
    let (digits, exponent) = grisu(value);
    let absolute = (exponent + digits.len() as i32 - 1).abs();
    let mut output = String::from(sign);
    if exponent >= 0 && absolute < 15 {
        output.extend(digits.iter().map(|digit| *digit as char));
        output.extend(std::iter::repeat_n('0', exponent as usize));
        output.push_str(".0");
    } else if exponent < 0 && (exponent > -7 || absolute < 10) {
        let offset = digits.len() as i32 + exponent;
        if offset <= 0 {
            output.push_str("0.");
            output.extend(std::iter::repeat_n('0', (-offset) as usize));
            output.extend(digits.iter().map(|digit| *digit as char));
        } else {
            for (index, digit) in digits.iter().enumerate() {
                if index == offset as usize {
                    output.push('.');
                }
                output.push(*digit as char);
            }
        }
    } else {
        let count = digits.len().min(18 - usize::from(negative));
        output.push(digits[0] as char);
        if count > 1 {
            output.push('.');
            output.extend(digits[1..count].iter().map(|digit| *digit as char));
        }
        output.push('e');
        output.push(if exponent + count as i32 - 1 < 0 {
            '-'
        } else {
            '+'
        });
        output.push_str(&absolute.to_string());
    }
    output
}
