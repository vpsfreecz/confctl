//! The caller publishes the core cluster list and obtains fresh full inventory
//! before rendering this opt-in list. There is no SSH, prompt or Nix evaluation.

use crate::{
    configuration::{
        FilePolicy, MutationGuard, NetbootInventorySettings, StateFiles, WriteReceipt,
    },
    domain::Inventory,
    error::ConfctlError,
};
use std::fmt::Write;

pub struct FeatureFiles<'a> {
    pub files: &'a StateFiles,
    pub settings: &'a NetbootInventorySettings,
    pub mutation: &'a MutationGuard,
}

pub fn render(inventory: &Inventory) -> Result<Vec<u8>, ConfctlError> {
    let mut output = String::from(
        "# This file is auto-generated on confctl rediscover, changes will be lost\n[\n",
    );
    for machine in &inventory.machines {
        if machine.carrier.is_none()
            && machine.attribute("netboot.enable") == serde_json::Value::Bool(true)
        {
            output.push_str("  ");
            output.push_str(&ruby_dump(&machine.name));
            output.push('\n');
        }
    }
    output.push_str("]\n");
    Ok(output.into_bytes())
}

// NixFormat's literal string branch uses Ruby String#dump, not JSON or a sorted
// name list. Keep the established generated bytes, including Unicode escapes.
fn ruby_dump(text: &str) -> String {
    let mut out = String::from("\"");
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\x0b' => out.push_str("\\v"),
            '\x0c' => out.push_str("\\f"),
            '\x08' => out.push_str("\\b"),
            '\x07' => out.push_str("\\a"),
            '\x1b' => out.push_str("\\e"),
            '#' if chars
                .peek()
                .is_some_and(|next| matches!(next, '{' | '$' | '@')) =>
            {
                out.push_str("\\#")
            }
            c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
            c if c.is_ascii() => {
                write!(&mut out, "\\x{:02X}", c as u32).expect("String write");
            }
            c if (c as u32) <= 0xffff => {
                write!(&mut out, "\\u{:04X}", c as u32).expect("String write");
            }
            c => {
                write!(&mut out, "\\u{{{:X}}}", c as u32).expect("String write");
            }
        }
    }
    out.push('"');
    out
}

/// Emit the normal replacement notice before calling this publication owner.
/// The operation skips this function entirely when the feature is disabled.
pub fn publish(ctx: &FeatureFiles<'_>, content: &[u8]) -> Result<WriteReceipt, ConfctlError> {
    if !ctx.settings.enable {
        return Err(ConfctlError::Configuration(
            "netboot inventory is disabled".into(),
        ));
    }
    ctx.files.require_mutation(ctx.mutation)?;
    let path = ctx.settings.output_file.as_ref().ok_or_else(|| {
        ConfctlError::Configuration("netbootInventory.outputFile is required when enabled".into())
    })?;
    ctx.files
        .replace(ctx.mutation, path, content, FilePolicy::GeneratedNix)
}

