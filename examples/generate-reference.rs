    #[test]
    fn every_route_group_and_schema_spelling_uses_real_public_help() {
        let rendered = cli_reference().unwrap();
        assert_eq!(schema::ROUTES.len(), 30);
        assert!(rendered.contains(&help_code(&help("").unwrap())));
        let mut groups = Vec::new();
        super::groups("", &mut groups);
        assert!(!groups.is_empty());
        for path in groups
            .iter()
            .map(String::as_str)
            .chain(schema::ROUTES.iter().copied())
        {
            assert_eq!(
                rendered.matches(&format!("### confctl {path}\n")).count(),
                1
            );
            assert!(rendered.contains(&help_code(&help(path).unwrap())));
            for spec in schema::options(path) {
                for name in std::iter::once(spec.name).chain(spec.aliases.iter().copied()) {
                    for negative in [false, true]
                        .into_iter()
                        .filter(|negative| !negative || spec.negatable)
                    {
                        let flag = if negative {
                            format!("--no-{name}")
                        } else {
                            spelling(name)
                        };
                        let mut args = path
                            .split_whitespace()
                            .map(OsString::from)
                            .collect::<Vec<_>>();
                        args.push(flag.clone().into());
                        match spec.kind {
                            schema::Kind::Switch(_) => {}
                            schema::Kind::Integer => args.push("1".into()),
                            _ => args.push(
                                if spec.name == "managed" {
                                    "all"
                                } else {
                                    "value"
                                }
                                .into(),
                            ),
                        }
                        args.push("--help".into());
                        assert!(
                            matches!(cli::parse(args), Ok(ParseOutcome::Display(d)) if d.code == 0),
                            "{path} {flag}"
                        );
                        assert!(rendered.contains(&format!("`{flag}`")));
                    }
                }
            }
        }
        assert!(rendered.contains("`--allow_shared`, `--allow-shared`"));
        assert!(rendered.contains("| `--changelog` | switch | `--no-changelog` | `true` |"));
        assert!(rendered.contains("| `--show-trace` | switch | `--no-show-trace` | `false` |"));
        assert!(rendered.contains("| signed integer | none | not specified |"));
    }

    #[test]
    fn only_help_line_end_spaces_are_removed_and_expression_payload_is_preserved() {
        assert_eq!(
            help_code(
                "  Usage: confctl  x   \n\taligned  columns \t \r\n\ntrailing\u{a0}  \nlast  "
            ),
            "```text\n  Usage: confctl  x\n\taligned  columns \t\r\n\ntrailing\u{a0}\nlast\n```\n\n"
        );
        let input = json!([{
            "name": "confctl.fixture",
            "type": "anything",
            "declarations": [],
            "default": {
                "_type": "literalExpression",
                "text": "  let  \n\tvalue = \"é\"; \t  \r\nin value  "
            }
        }]);
        let rendered = options_reference(&serde_json::to_vec(&input).unwrap()).unwrap();
        assert!(rendered.contains(
            "Default: Nix expression\n\n```nix\n  let  \n\tvalue = \"é\"; \t  \r\nin value  \n```\n\n"
        ));
    }

    #[test]
    fn exported_option_semantics_groups_markup_and_declaration_labels_survive() {
        let rendered =
            options_reference(include_bytes!("../tests/fixtures/reference-options.json")).unwrap();
        let settings = rendered.find("## CONFCTL SETTINGS").unwrap();
        let machines = rendered.find("## MACHINE CONFIGURATION").unwrap();
        let systems = rendered.find("## MACHINE SYSTEM CONFIGURATION").unwrap();
        assert!(
            settings
                < rendered
                    .find(&format!("### {}", inline("confctl.fixture.absent")))
                    .unwrap()
        );
        assert!(
            rendered
                .find(&format!("### {}", inline("confctl.fixture.false")))
                .unwrap()
                < machines
        );
        assert!(
            machines
                < rendered
                    .find(&format!("### {}", inline("cluster.fixture")))
                    .unwrap()
        );
        assert!(
            rendered
                .find(&format!("### {}", inline("cluster.fixture")))
                .unwrap()
                < systems
        );
        for name in [
            "confctl.carrier.fixture",
            "confctl.programs.fixture",
            "confctl.inputsInfo",
            "confctl.configurationInfo",
        ] {
            assert!(systems < rendered.find(&format!("### {}", inline(name))).unwrap());
        }
        for exact in [
            "Default: not exported",
            "```json\nnull\n```",
            "```json\nfalse\n```",
            "```nix\n{ pkgs, ... }: pkgs.hello\n```",
            "`cluster.fixture` & `false` — žluťoučký",
            "<confctl/nix/modules/cluster/fixture.nix>",
            "/external/module.nix",
        ] {
            assert!(rendered.contains(exact), "missing {exact}");
        }
        let mut input: Vec<Value> =
            serde_json::from_slice(include_bytes!("../tests/fixtures/reference-options.json"))
                .unwrap();
        input.reverse();
        assert_eq!(
            rendered,
            options_reference(&serde_json::to_vec(&input).unwrap()).unwrap()
        );
        assert_eq!(
            description("&lt;literal&gt;é&#x21;&lt;/literal&gt; &#39; &amp; &unknown;"),
            "`é!` ' & &unknown;"
        );
        let placeholder =
            json!([{"name":"cluster.<name>.fixture","type":"string","declarations":[]}]);
        assert!(
            options_reference(&serde_json::to_vec(&placeholder).unwrap())
                .unwrap()
                .contains("### ` cluster.<name>.fixture `")
        );
    }

