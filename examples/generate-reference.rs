    #[test]
    fn malformed_exports_are_rejected_before_any_stdout_and_check_never_writes() {
        let scratch = tempfile::tempdir().unwrap();
        let input = scratch.path().join("options.json");
        let target = scratch.path().join("manual.md");
        let good = json!({"name":"confctl.fixture","type":"anything","declarations":[]});
        for bad in [
            json!({}),
            json!([false]),
            json!([{"name":false}]),
            json!([{"name":"other.value","type":"bool","declarations":[]}]),
            json!([{"name":"confctl.fixture","type":"bool","declarations":[false]}]),
            json!([{"name":"confctl.fixture","type":"bool","declarations":[],"default":{"_type":"unknown","text":"x"}}]),
            json!([{"name":"confctl.fixture","type":"bool","declarations":[],"default":{"_type":"literalExpression","text":false}}]),
            json!([good.clone(), good.clone()]),
        ] {
            fs::write(&input, serde_json::to_vec(&bad).unwrap()).unwrap();
            let mut output = Vec::new();
            assert!(
                maintain(
                    &["options".into(), input.clone().into_os_string()],
                    &mut output
                )
                .is_err()
            );
            assert!(output.is_empty());
        }
        let left = json!({"z":false,"a":[null,"ž"]});
        let right = json!({"a":[null,"ž"],"z":false});
        assert_eq!(
            option_value(Some(&left)).unwrap(),
            option_value(Some(&right)).unwrap()
        );
        assert!(option_value(Some(&json!([{"_type":"literalExpression","text":"x"}]))).is_err());
        fs::write(&input, serde_json::to_vec(&json!([good])).unwrap()).unwrap();
        let mut generated = Vec::new();
        maintain(
            &["options".into(), input.clone().into_os_string()],
            &mut generated,
        )
        .unwrap();
        fs::write(&target, &generated).unwrap();
        let args = [
            "options".into(),
            input.into_os_string(),
            "--check".into(),
            target.clone().into_os_string(),
        ];
        let mut output = Vec::new();
        maintain(&args, &mut output).unwrap();
        assert!(output.is_empty());
        fs::write(&target, b"drift").unwrap();
        assert!(maintain(&args, &mut output).is_err());
        assert_eq!(fs::read(target).unwrap(), b"drift");
    }
